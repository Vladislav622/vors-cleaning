export function pick<T>(arr: T[], avoid?: T): T {
  if (arr.length <= 1) return arr[0];
  let v = arr[Math.floor(Math.random() * arr.length)];
  if (v === avoid) v = arr[(arr.indexOf(v) + 1) % arr.length];
  return v;
}
